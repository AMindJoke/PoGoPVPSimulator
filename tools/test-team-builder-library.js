const assert = require("node:assert/strict");
const Team = require("../src/team-builder/team-builder-state.js");
const Library = require("../src/team-builder/team-builder-library.js");
const data = new Map();
let sequence = 0, fail = false;
const storage = { getItem: key => data.get(key) || null, setItem: (key, text) => { if (fail) throw new Error("QuotaExceededError"); data.set(key, text); } };
const store = Library.createStore(storage, () => `id-${++sequence}`);
const member = { pokemonId: "mimikyu", dex: 778, name: "Mimikyu", types: ["ghost", "fairy"], fastMoveId: "SHADOW_CLAW", chargedMoveIds: ["SHADOW_SNEAK", "PLAY_ROUGH"], build: { profile: "custom", ivAtk: 3, ivDef: 12, ivHp: 14 } };
const state = Team.createState({ team: [member], analysisConfig: { shields: "2-2", meta: "great-league-current" } });
const snapshot = { state, comparisonBaseline: state.team };
assert.deepEqual(store.read().teams, []);
let saved = store.add(" Coppa Ω ", snapshot);
const original = saved.teams[0];
assert.equal(original.name, "Coppa Ω");
assert.deepEqual(Library.snapshot(original), snapshot, "Drafts, custom moves/IVs, shields and comparison must survive storage.");
saved.teams[0].state.team[0].build.ivAtk = 15;
assert.equal(store.read().teams[0].state.team[0].build.ivAtk, 3, "Published entries cannot mutate storage.");
store.add("Coppa Ω", snapshot);
assert.equal(store.read().teams[0].name, "Coppa Ω (2)");
store.rename(original.id, "Team A");
const exported = store.export();
assert.deepEqual(Library.parse(exported), store.read());
assert.equal(store.merge(Library.parse(exported)).teams.length, 2, "Repeated import should be idempotent.");
const conflict = Library.parse(exported); conflict.teams[0].state.team[0].build.ivHp = 13;
store.merge(conflict);
assert.equal(store.read().teams.length, 3, "Conflicting imports must add entries instead of overwriting.");
const before = store.export(); fail = true;
assert.throws(() => store.add("Should not exist", snapshot), /Could not save/);
assert.equal(store.export(), before, "Quota failures must preserve the complete old library."); fail = false;
const secondTab = Library.createStore(storage, () => `id-${++sequence}`);
secondTab.add("Other tab", snapshot); store.add("This tab", snapshot);
assert.equal(store.read().teams.length, 5, "Editing another tab must not lose previously saved teams.");
store.remove(original.id); assert.ok(!store.read().teams.some(team => team.id === original.id));
store.merge({ schemaVersion: 1, teams: [original] }); assert.ok(store.read().teams.some(team => team.name === "Coppa Ω"));
const pristine = store.export();
assert.throws(() => Library.parse("not json"), /valid team JSON/);
assert.throws(() => Library.parse("x".repeat(Library.MAX_BYTES + 1)), /smaller than 1 MB/);
assert.throws(() => Library.parse(JSON.stringify({ schemaVersion: 2, teams: [] })), /incompatible/);
const malformed = Library.parse(pristine); malformed.teams[0].state.team[0].build.ivAtk = 99;
assert.throws(() => store.merge(malformed), /IVs are invalid/);
assert.equal(store.export(), pristine, "Invalid imports must be atomic.");
data.set(Library.KEY, "damaged");
assert.throws(() => store.read()); assert.throws(() => store.add("No overwrite", snapshot));
assert.equal(data.get(Library.KEY), "damaged", "Corrupt stored data must remain recoverable, never silently reset.");
console.log("Saved team library tests passed.");
